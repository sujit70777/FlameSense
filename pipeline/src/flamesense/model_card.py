"""docs/MODEL_CARD.md and evaluation charts (PLAN.md Phase 5 steps 2 and 5)."""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from flamesense.evaluate import COLOR_AXIS, COLOR_EMBER, COLOR_MICROG, spread_oof

WEAK_AUC = 0.7
WEAK_R2 = 0.3


def fmt(value: float | None, digits: int = 3) -> str:
    """Format a metric for the card; '—' when unavailable."""
    return "—" if value is None else f"{value:.{digits}g}"


def sustain_section(m: dict) -> list[str]:
    """Markdown lines describing the sustain classifier's metrics."""
    lines = ["### Sustain (chance a flame keeps burning)", ""]
    if not m["available"]:
        return lines + [f"**Not trained.** {m['reason']}", ""]
    lines += [
        "| Metric | Value | Plain meaning |",
        "|---|---|---|",
        f"| Rows / test series | {m['n_rows']} / {m['n_groups']} | Data used, independent groups |",
        f"| Cross-validation | {m['cv']} | Whole test series held out |",
        f"| ROC-AUC | {fmt(m['roc_auc'])} | 0.5 = coin flip, 1 = perfect ranking |",
        f"| Brier score | {fmt(m['brier'])} | Lower is better |",
        f"| Baseline Brier (class prior) | {fmt(m['baseline_brier'])} | Always guessing the average |",
        f"| Accuracy at 0.5 | {fmt(m['accuracy_at_0_5'])} | Share of runs classified right |",
        "",
    ]
    weak = m["roc_auc"] < WEAK_AUC or m["brier"] >= m["baseline_brier"]
    if weak:
        lines += [("**These metrics are weak.** The classifier barely beats guessing the class "
                  "average; treat its probabilities as rough."), ""]
    return lines


def spread_section(m: dict) -> list[str]:
    """Markdown lines describing the spread quantile models' metrics."""
    lines = ["### Spread rate (10th, 50th, 90th percentile)", ""]
    if not m["available"]:
        return lines + [f"**Not trained.** {m['reason']}", ""]
    lines += [
        "| Metric | Value | Plain meaning |",
        "|---|---|---|",
        f"| Rows / test series | {m['n_rows']} / {m['n_groups']} | Data used, independent groups |",
        f"| Cross-validation | {m['cv']} | Whole test series held out |",
        f"| MAE | {fmt(m['mae_mm_s'])} mm/s | Typical error of the median prediction |",
        f"| Baseline MAE (training median) | {fmt(m['baseline_mae_mm_s'])} mm/s | No-model error |",
        f"| Median absolute % error | {fmt(None if m['median_ape'] is None else m['median_ape'] * 100)}% | |",
        f"| R² (log scale) | {fmt(m['r2_log'])} | 1 = perfect, 0 = no better than the mean |",
        f"| 80% interval coverage | {fmt(m['interval_80_coverage'])} | Should be near 0.8 |",
        f"| Physics MAE | {fmt(m['physics_mae_mm_s'])} mm/s | Thin-fuel theory on applicable rows |",
        "",
    ]
    if m["r2_log"] < WEAK_R2 or m["mae_mm_s"] >= m["baseline_mae_mm_s"]:
        lines += [("**These metrics are weak.** The spread model does not clearly beat the "
                  "training median; use the interval, not the point value."), ""]
    return lines


def warning_lines(metrics: dict) -> list[str]:
    """Bulleted warnings from both tasks, or '- None'."""
    warnings = metrics["sustain"]["warnings"] + metrics["spread"]["warnings"]
    return [f"- {w}" for w in warnings] or ["- None"]


def write_model_card(metrics: dict, summaries: dict, path: Path) -> Path:
    """Write docs/MODEL_CARD.md from metrics and training summaries."""
    feats = sorted(set(summaries["sustain"]["features"]) | set(summaries["spread"]["features"]))
    lines = [
        "# FlameSense — Model card", "",
        "Generated by `python -m flamesense.cli evaluate`. Do not edit by hand.", "",
        "## Intended use",
        ("Research and education: exploring how oxygen, pressure, airflow, gravity and material "
        "affect whether a flame keeps burning and how fast it spreads, within the range NASA tested."), "",
        "## Not intended for",
        ("Operational fire-safety decisions, material qualification, or certification of any "
        "spacecraft, habitat, building or vehicle. FlameSense is not a certified safety system."), "",
        "## Data",
        ("Only real experiment runs from `data/raw/` and `data/manual/` with a source citation. "
        "No synthetic rows. Rows flagged `suspect` are excluded from training. No imputation: "
        "rows missing a selected feature are dropped."), "",
        f"Features used: {', '.join(feats) if feats else 'none (no model trained)'}.", "",
        "## Metrics (out-of-fold, grouped cross-validation)", "",
        *sustain_section(metrics["sustain"]),
        *spread_section(metrics["spread"]),
        "## Warnings", "",
        *(warning_lines(metrics)), "",
        "## Limitations",
        (f"- Small dataset: {metrics['sustain']['n_rows']} usable runs for the burning model "
        f"and {metrics['spread']['n_rows']} for spread rate."),
        "- Test-series dependence: runs from one campaign share hardware and procedures.",
        ("- Extrapolation: outside the tested ranges (and at Moon or Mars gravity, where there "
        "is little or no data) predictions are extrapolations and are flagged as such."),
        ("- Physics model simplifications: the thin-fuel reference ignores finite-rate chemistry "
        "and radiation and over-predicts spread near extinction."),
        "- No operational use: see 'Not intended for'.", "",
        "## Ethical note",
        ("Fire safety affects lives. FlameSense shows data support and extrapolation warnings next "
        "to every prediction so that nobody mistakes an estimate for a safety guarantee."), "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def _style(ax, title: str, xlabel: str, ylabel: str) -> None:
    """Sentence-case title and unit-labelled axes in DESIGN.md colours."""
    ax.set_title(title, loc="left")
    ax.set_xlabel(xlabel, color=COLOR_AXIS)
    ax.set_ylabel(ylabel, color=COLOR_AXIS)
    ax.grid(axis="y", alpha=0.3)


def write_charts(metrics: dict, summaries: dict, img_dir: Path) -> list[Path]:
    """calibration.png and spread_pred_vs_obs.png (only for available tasks)."""
    img_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    bins = metrics["sustain"]["calibration_bins"]
    if metrics["sustain"]["available"] and bins:
        fig, ax = plt.subplots(figsize=(6, 5))
        ax.plot([0, 1], [0, 1], linestyle="--", color=COLOR_AXIS, label="Perfect calibration")
        ax.plot([b[0] for b in bins], [b[1] for b in bins], marker="o", color=COLOR_MICROG,
                label="FlameSense")
        _style(ax, "Predicted vs observed chance of burning",
               "Predicted probability", "Observed share that kept burning")
        ax.legend()
        written.append(_save(fig, img_dir / "calibration.png"))
    if metrics["spread"]["available"]:
        truth, q10, q50, q90 = spread_oof(summaries["spread"])
        fig, ax = plt.subplots(figsize=(6, 5))
        ax.errorbar(truth, q50, yerr=[q50 - q10, q90 - q50], fmt="o", color=COLOR_MICROG,
                    ecolor=COLOR_MICROG, alpha=0.6, markersize=4, label="Median and 80% range")
        lo, hi = float(np.min(truth)), float(np.max(truth))
        ax.plot([lo, hi], [lo, hi], linestyle="--", color=COLOR_EMBER, label="1:1")
        ax.set_xscale("log")
        ax.set_yscale("log")
        _style(ax, "Predicted vs observed spread rate",
               "Observed (mm/s, log scale)", "Predicted (mm/s, log scale)")
        ax.legend()
        written.append(_save(fig, img_dir / "spread_pred_vs_obs.png"))
    return written


def _save(fig, path: Path) -> Path:
    """Save and close a matplotlib figure."""
    fig.tight_layout()
    fig.savefig(path, dpi=150, facecolor="white")
    plt.close(fig)
    return path


def load_json(path: Path) -> dict:
    """Read a JSON file."""
    return json.loads(path.read_text(encoding="utf-8"))
