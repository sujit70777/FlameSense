def placeholders(text: str) -> list[str]:
    """Placeholder names in an ICU message, in order of first use."""
    seen: list[str] = []
    for name in re.findall(r"\{(\w+)\}", text):
        if name not in seen:
            seen.append(name)
    return seen


def build(lang: str) -> dict:
    """ARB content for 'en' or 'bn'."""
    arb: dict = {"@@locale": lang}
    keys = set()
    for key, en, bn, desc in S:
        if key in keys:
            raise SystemExit(f"duplicate key {key}")
        keys.add(key)
        value = en if lang == "en" else bn
        if placeholders(en) != placeholders(bn) and set(placeholders(en)) != set(placeholders(bn)):
            raise SystemExit(f"placeholder mismatch in {key}")
        arb[key] = value
        meta: dict = {"description": desc}
        if placeholders(en):
            meta["placeholders"] = {p: {"type": "String"} for p in placeholders(en)}
        if lang == "bn" and key not in REVIEWED_BN:
            meta["x-review"] = "bn-pending"
        arb[f"@{key}"] = meta
    return arb


def main() -> None:
    """Write both ARB files next to this script's app."""
    out = Path(__file__).resolve().parents[1] / "lib" / "l10n"
    for lang in ("en", "bn"):
        path = out / f"app_{lang}.arb"
        path.write_text(json.dumps(build(lang), ensure_ascii=False, indent=2) + "\n", "utf-8")
        print(f"wrote {path} ({len(S)} keys)")


if __name__ == "__main__":
    main()
